import type { Booking, BookingRequest, Folio } from '@/types';
import { dateRange, mmk } from '@/lib/format';

const BASE_STYLE = `
  body { font-family: 'Segoe UI', Arial, sans-serif; color:#111c2d; padding:32px; font-size:13px; }
  h1 { font-size:20px; margin:0 0 2px; }
  .muted { color:#75777e; }
  .head { border-bottom:2px solid #0e1c32; padding-bottom:12px; margin-bottom:16px; }
  .row { display:flex; justify-content:space-between; gap:16px; padding:6px 0; border-bottom:1px solid #e7eeff; }
  .row.total { font-weight:700; border-bottom:2px solid #0e1c32; }
  .badge { display:inline-block; padding:2px 8px; border-radius:999px; background:#86f2e4; font-size:11px; margin-right:4px; }
  .badge.amber { background:#ffdcc3; }
  .footer { margin-top:28px; color:#75777e; font-size:11px; }
  @media print { body { padding:0 } }
`;

function openPrintWindow(title: string, inner: string): void {
  const win = window.open('', '_blank', 'width=720,height=960');
  if (!win) return;
  win.document.open();
  win.document.write(
    `<!doctype html><html><head><meta charset="utf-8"><title>${title}</title>` +
      `<style>${BASE_STYLE}</style></head><body>${inner}</body></html>`,
  );
  win.document.close();
  win.focus();
  win.setTimeout(() => win.print(), 250);
}

/** Render a KBZPay slip (with its uploaded image) into a print window. */
export function printSlip(
  slip: NonNullable<BookingRequest['slip']>,
  amount: number,
  imageSrc?: string,
): void {
  openPrintWindow(
    'KBZPay Bank Slip',
    `
    <div class="head"><h1>KBZPay · Bank Slip</h1><p class="muted">Payment verification record</p></div>
    ${imageSrc ? `<img src="${imageSrc}" alt="Uploaded bank slip" style="width:100%;max-width:520px;border:1px solid #e7eeff;border-radius:12px;margin:0 auto 16px;display:block" />` : ''}
    <div class="row"><span>Transaction Ref</span><span>${slip.txnRef}</span></div>
    <div class="row"><span>Amount</span><span>${mmk(amount)}</span></div>
    <div class="row"><span>Payer</span><span>${slip.payer}</span></div>
    <div class="row"><span>Recipient</span><span>${slip.recipient}</span></div>
    <div class="row"><span>Timestamp</span><span>${slip.timestamp}</span></div>
    <div class="row total"><span>Status</span><span>Verified · Amount matched</span></div>
    <p class="footer">StayEase · Yangon Heritage · Front Desk Ops — generated by staff console</p>`,
  );
}

